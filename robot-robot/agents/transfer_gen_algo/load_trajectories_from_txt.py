"""
Load trajectories from TXT files generated by Antonio's genetic algorithm.
File format: [joint_positions, joint_velocities, end_effector_position]
- 2-DoF: 6 columns (θ1, θ2, dθ1, dθ2, eff_x, eff_y)
- 3-DoF: 8 columns (θ1, θ2, θ3, dθ1, dθ2, dθ3, eff_x, eff_y)

Usage:
    python -m lsunn.data.load_trajectories_from_txt
"""

import numpy as np
import pickle
from pathlib import Path
from tqdm import tqdm

# Dimensions
ARM_OBS_2DOF = 6   # [θ1/π, θ2/π, dθ1/ω, dθ2/ω, eff_x/r, eff_y/r]
ARM_OBS_3DOF = 8   # [θ1/π, θ2/π, θ3/π, dθ1/ω, dθ2/ω, dθ3/ω, eff_x/r, eff_y/r]

MAX_REACH = 3.0
OMEGA_MAX = 2.0  # rad/s
# When a single TXT contains a very long trajectory (e.g. 100k points),
# split it into multiple overlapping windows so we can produce many
# sampled segments for training instead of a single segment per file.
WINDOW_SIZE = 500
WINDOW_STRIDE = 250


def normalize_angle(angle_rad: np.ndarray) -> np.ndarray:
    """Normalize angle to [-π, π] then divide by π → [-1, 1]"""
    # Wrap to [-π, π]
    wrapped = ((angle_rad + np.pi) % (2 * np.pi)) - np.pi
    return wrapped / np.pi


def normalize_velocity(velocity_rad_s: np.ndarray) -> np.ndarray:
    """Normalize velocity by ω_max → [-1, 1]"""
    return np.clip(velocity_rad_s / OMEGA_MAX, -1.0, 1.0)


def normalize_position(pos_m: np.ndarray) -> np.ndarray:
    """Normalize position by max_reach → [-1, 1]"""
    return np.clip(pos_m / MAX_REACH, -1.0, 1.0)


def load_2dof_txt(file_path: Path) -> np.ndarray:
    """
    Load 2-DoF trajectory from TXT file.
    Format: [θ1, θ2, dθ1, dθ2, eff_x, eff_y]
    Returns normalized arm observation array (N, 6)
    """
    data = np.loadtxt(file_path, delimiter=None)
    
    if data.ndim == 1:
        data = data.reshape(1, -1)
    
    # Extract columns
    theta1_rad = data[:, 0]
    theta2_rad = data[:, 1]
    dtheta1_rad_s = data[:, 2]
    dtheta2_rad_s = data[:, 3]
    eff_x_m = data[:, 4]
    eff_y_m = data[:, 5]
    
    # Normalize
    theta1_norm = normalize_angle(theta1_rad)
    theta2_norm = normalize_angle(theta2_rad)
    dtheta1_norm = normalize_velocity(dtheta1_rad_s)
    dtheta2_norm = normalize_velocity(dtheta2_rad_s)
    eff_x_norm = normalize_position(eff_x_m)
    eff_y_norm = normalize_position(eff_y_m)
    
    # Stack
    arm_obs = np.stack([
        theta1_norm, theta2_norm,
        dtheta1_norm, dtheta2_norm,
        eff_x_norm, eff_y_norm
    ], axis=-1)
    
    return arm_obs.astype(np.float32)


def load_3dof_txt(file_path: Path) -> np.ndarray:
    """
    Load 3-DoF trajectory from TXT file.
    Format: [θ1, θ2, θ3, dθ1, dθ2, dθ3, eff_x, eff_y]
    Returns normalized arm observation array (N, 8)
    """
    # Accept any whitespace (spaces or tabs) as delimiter to support
    # TXT files that may use spaces instead of tabs.
    data = np.loadtxt(file_path, delimiter=None)
    
    if data.ndim == 1:
        data = data.reshape(1, -1)
    
    # Extract columns
    theta1_rad = data[:, 0]
    theta2_rad = data[:, 1]
    theta3_rad = data[:, 2]
    dtheta1_rad_s = data[:, 3]
    dtheta2_rad_s = data[:, 4]
    dtheta3_rad_s = data[:, 5]
    eff_x_m = data[:, 6]
    eff_y_m = data[:, 7]
    
    # Normalize
    theta1_norm = normalize_angle(theta1_rad)
    theta2_norm = normalize_angle(theta2_rad)
    theta3_norm = normalize_angle(theta3_rad)
    dtheta1_norm = normalize_velocity(dtheta1_rad_s)
    dtheta2_norm = normalize_velocity(dtheta2_rad_s)
    dtheta3_norm = normalize_velocity(dtheta3_rad_s)
    eff_x_norm = normalize_position(eff_x_m)
    eff_y_norm = normalize_position(eff_y_m)
    
    # Stack
    arm_obs = np.stack([
        theta1_norm, theta2_norm, theta3_norm,
        dtheta1_norm, dtheta2_norm, dtheta3_norm,
        eff_x_norm, eff_y_norm
    ], axis=-1)
    
    return arm_obs.astype(np.float32)


def load_all_trajectories(data_dir: Path) -> tuple:
    """
    Load all 2-DoF and 3-DoF trajectory files and create paired segments.
    
    Returns:
        segments_2dof: List of trajectory segments (each of varying length)
        segments_3dof: List of trajectory segments
        actions_2dof: List of actions (to be generated from velocities)
        actions_3dof: List of actions
    """
    # Find all files
    files_2dof = sorted(data_dir.glob("*2dofs*.txt"))
    files_3dof = sorted(data_dir.glob("*3dofs*.txt"))
    
    if not files_2dof or not files_3dof:
        raise FileNotFoundError(f"No trajectory files found in {data_dir}")
    
    print(f"Found {len(files_2dof)} 2-DoF files and {len(files_3dof)} 3-DoF files")
    
    segments_2dof = []
    segments_3dof = []
    actions_2dof = []
    actions_3dof = []
    
    # Process each pair (assuming same base name)
    for f2 in tqdm(files_2dof, desc="Loading trajectories"):
        # Find matching 3-DoF file (same index or similar name)
        # Assuming files are in same order
        idx = files_2dof.index(f2)
        if idx < len(files_3dof):
            f3 = files_3dof[idx]
        else:
            continue
        
        # Load trajectories
        traj_2dof = load_2dof_txt(f2)
        traj_3dof = load_3dof_txt(f3)
        
        # Ensure same length (trim if necessary)
        min_len = min(len(traj_2dof), len(traj_3dof))
        if min_len < 10:
            continue
        
        traj_2dof = traj_2dof[:min_len]
        traj_3dof = traj_3dof[:min_len]
        
        # Generate actions from velocities. The trajectories' velocity columns are
        # already normalized in [-1, 1], so explicitly represent actions as
        # joint-velocity actions and cast to float32.
        vel_2dof = traj_2dof[:, 2:4]  # dθ1_norm, dθ2_norm
        action_2dof = vel_2dof.astype(np.float32)

        # For 3-DoF
        vel_3dof = traj_3dof[:, 3:6]  # dθ1_norm, dθ2_norm, dθ3_norm
        action_3dof = vel_3dof.astype(np.float32)
        
        # If trajectory is long, split into overlapping windows so we get
        # multiple segments from a single TXT file (useful for 100k points)
        if min_len <= WINDOW_SIZE:
            segments_2dof.append(traj_2dof)
            segments_3dof.append(traj_3dof)
            actions_2dof.append(action_2dof)
            actions_3dof.append(action_3dof)
        else:
            # Slide a window over the trajectory
            start = 0
            while start + WINDOW_SIZE <= min_len:
                end = start + WINDOW_SIZE
                segments_2dof.append(traj_2dof[start:end])
                segments_3dof.append(traj_3dof[start:end])
                actions_2dof.append(action_2dof[start:end])
                actions_3dof.append(action_3dof[start:end])
                start += WINDOW_STRIDE
            # If there is a tail shorter than WINDOW_SIZE, include last window
            if start < min_len and (min_len - WINDOW_SIZE) % WINDOW_STRIDE != 0:
                segments_2dof.append(traj_2dof[-WINDOW_SIZE:])
                segments_3dof.append(traj_3dof[-WINDOW_SIZE:])
                actions_2dof.append(action_2dof[-WINDOW_SIZE:])
                actions_3dof.append(action_3dof[-WINDOW_SIZE:])
    
    print(f"Loaded {len(segments_2dof)} valid trajectory pairs")
    
    return segments_2dof, segments_3dof, actions_2dof, actions_3dof


def build_sliding_history(states, history_len=4):
    n, d = states.shape
    history = np.zeros((n, d * history_len), dtype=np.float32)

    for t in range(n):
        frames = []
        for k in range(history_len):
            idx = max(0, t - history_len + 1 + k)
            frames.append(states[idx])
        history[t] = np.concatenate(frames)

    return history


def create_sampled_segments(segments_2dof, segments_3dof, actions_2dof, actions_3dof,
                            num_samples: int = 50):
    """
    Create fixed-length segments using spatial sampling and sliding history.
    """
    # Use local sampling utilities provided in this package
    from .utils import spatial_sampling_aligned
    
    all_s2_ss = []
    all_s3_ss = []
    all_a2_ss = []
    all_a3_ss = []
    
    all_s2_history = []
    all_s3_history = []
    
    for s2, s3, a2, a3 in tqdm(zip(segments_2dof, segments_3dof, 
                                     actions_2dof, actions_3dof),
                                desc="Sampling segments", total=len(segments_2dof)):
        
        if len(s2) < num_samples // 2:
            continue
        
        # Spatial sampling (aligned by end-effector path)
        s2_ss, a2_ss = spatial_sampling_aligned(s2, a2, num_samples, use_effector=True)
        s3_ss, a3_ss = spatial_sampling_aligned(s3, a3, num_samples, use_effector=True)
        
        s2_hist = build_sliding_history(s2_ss, history_len=4)
        s3_hist = build_sliding_history(s3_ss, history_len=4)
        
        # Validate
        if (s2_ss.shape[0] == num_samples and s3_ss.shape[0] == num_samples and
            s2_hist.shape[0] == num_samples and s3_hist.shape[0] == num_samples):
            
            all_s2_ss.append(s2_ss)
            all_s3_ss.append(s3_ss)
            all_a2_ss.append(a2_ss)
            all_a3_ss.append(a3_ss)
            
            all_s2_history.append(s2_hist)
            all_s3_history.append(s3_hist)
    
    print(f"Created {len(all_s2_ss)} sampled segments of length {num_samples}")
    
    return (np.stack(all_s2_ss), np.stack(all_s3_ss),
            np.stack(all_a2_ss), np.stack(all_a3_ss),
            np.stack(all_s2_history), np.stack(all_s3_history))


def main():
    # Paths
    data_dir = Path("./data/DIRECT_GEN_ALGO")
    output_dir = Path("./data/DIRECT_GEN_ALGO")
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Load raw trajectories
    print("Loading trajectory files...")
    segments_2dof, segments_3dof, actions_2dof, actions_3dof = load_all_trajectories(data_dir)
    
    # Create sampled segments
    print("\nCreating sampled segments...")
    (s2_ss, s3_ss, a2_ss, a3_ss,
     s2_hist, s3_hist) = create_sampled_segments(
        segments_2dof, segments_3dof, actions_2dof, actions_3dof,
        num_samples=50
    )
    
    # Save trajectories
    trajectories = {
        'segments_2dof': s2_ss,
        'segments_3dof': s3_ss,
        'segments_actions_2dof': a2_ss,
        'segments_actions_3dof': a3_ss,
        'segments_2dof_history': s2_hist,
        'segments_3dof_history': s3_hist,
        'metadata': {
            'n_segments': len(s2_ss),
            'seq_len': 50,
            'arm_size_2dof': ARM_OBS_2DOF,
            'arm_size_3dof': ARM_OBS_3DOF,
            'source': 'genetic_algorithm',
            'action_representation': 'joint_velocity',
            'description': 'Trajectories generated by Antonio using genetic algorithm',
        }
    }
    
    # Save
    output_path = output_dir / "trajectories_aligned_ss.pkl"
    with open(output_path, 'wb') as f:
        pickle.dump(trajectories, f)
    
    print(f"\n✓ Saved trajectories to {output_path}")
    print(f"  Total segments: {len(s2_ss)}")
    print(f"  Shapes: s2={s2_ss.shape}, s3={s3_ss.shape}")
    print(f"  History shapes: s2_hist={s2_hist.shape}, s3_hist={s3_hist.shape}")


if __name__ == "__main__":
    main()
